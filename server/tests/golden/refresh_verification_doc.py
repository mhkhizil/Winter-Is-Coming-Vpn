"""Splices the generated case table into BLAKE2S_VERIFICATION.md.

Keeps the hand-written prose above the `## Appendix` marker and replaces the
appendix body with the freshly generated table (so the record always matches the
last verifier run).

Run: python refresh_verification_doc.py
"""

import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DOC = os.path.join(HERE, "BLAKE2S_VERIFICATION.md")
TABLE = os.path.join(HERE, "work", "blake2s_table.md")
DRIVER = os.path.join(HERE, "work", "blake2s_driver.exe")
MARKER = "## Appendix: generated per-case table"

INTRO = [
    "## Appendix: generated per-case table",
    "",
    "Generated by `verify_blake2s.py`; do not edit by hand.",
    "",
    "```",
    "cd server/tests/golden",
    "python verify_blake2s.py --driver work/blake2s_driver.exe "
    "--markdown work/blake2s_table.md",
    "python refresh_verification_doc.py",
    "```",
    "",
]


def main() -> int:
    if not os.path.isfile(TABLE):
        print(f"missing {TABLE}; run verify_blake2s.py first")
        return 2
    with open(DOC, encoding="utf-8-sig") as f:
        prose = f.read()
    head, sep, _ = prose.partition(MARKER)
    if not sep:
        print(f"marker {MARKER!r} not found in {DOC}")
        return 2
    with open(TABLE, encoding="utf-8") as f:
        table = f.read()
    with open(DOC, "w", encoding="utf-8") as f:
        f.write(head + "\n".join(INTRO) + "\n" + table)
    print(f"[doc  ] refreshed {DOC}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
