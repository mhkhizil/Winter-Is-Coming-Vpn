"""Known-answer vectors for PBKDF2-HMAC-SHA256 (RFC 8018), for C++ test data.

The point of this script is independence: it derives the expected values with
Python's ``hashlib.pbkdf2_hmac``, a completely different code base from
``vpn::crypto::pbkdf2_sha256`` in ``server/src/crypto``. A test that compares the
C++ output against these strings therefore checks the implementation rather than
itself.

Before printing anything the script verifies hashlib against the published
PBKDF2-HMAC-SHA256 test vectors (P="password", S="salt", c=1/2/4096), so a broken
or patched Python cannot silently produce a wrong "golden" file.

Usage
  python scripts/gen_pbkdf2_vectors.py                 # C++ table (default)
  python scripts/gen_pbkdf2_vectors.py --format text   # human readable
  python scripts/gen_pbkdf2_vectors.py --format json   # machine readable
  python scripts/gen_pbkdf2_vectors.py --password secret --iterations 120000

Every password is ASCII, every hex string is lowercase, and the output is
deterministic: running it twice produces byte-identical text, so the result can
be committed as a golden file and diffed.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys

DEFAULT_PASSWORD = "correct horse battery staple"
DEFAULT_SALT_HEX = "00112233445566778899aabbccddeeff"

# (name, password, salt_hex, iterations, dklen)
#
# The first four are the published vectors for PBKDF2-HMAC-SHA256; the first
# three are also used by the self-check below. The rest cover the parameters this
# project actually ships: the login work factor (120000), the cheap values a test
# store may use (1, 2, 1000), a password that spans a hash block, and an output
# longer than one block so the block chaining (T_1 || T_2 || ...) is exercised.
VECTORS = [
    ("rfc-c1", "password", "73616c74", 1, 32),
    ("rfc-c2", "password", "73616c74", 2, 32),
    ("rfc-c4096", "password", "73616c74", 4096, 32),
    ("rfc-long-password", "passwordPASSWORDpassword",
     "73616c7453414c5473616c7453414c5473616c7453414c5473616c7453414c5473616c74",
     4096, 40),
    ("battery-c1", DEFAULT_PASSWORD, DEFAULT_SALT_HEX, 1, 32),
    ("battery-c2", DEFAULT_PASSWORD, DEFAULT_SALT_HEX, 2, 32),
    ("battery-c1000", DEFAULT_PASSWORD, DEFAULT_SALT_HEX, 1000, 32),
    ("battery-c120000", DEFAULT_PASSWORD, DEFAULT_SALT_HEX, 120000, 32),
    ("login-work-factor", "admin-password", DEFAULT_SALT_HEX, 120000, 32),
    ("two-blocks", "second factor", "ffeeddccbbaa99887766554433221100", 1000, 64),
    ("block-boundary", "x" * 64, "00112233445566778899aabbccddeeff", 10, 32),
    ("empty-password", "", DEFAULT_SALT_HEX, 1000, 32),
]

# Published vectors: (password, salt bytes, iterations, dklen, expected hex).
SELF_CHECK = [
    ("password", b"salt", 1, 32,
     "120fb6cffcf8b32c43e7225256c4f837a86548c92ccc35480805987cb70be17b"),
    ("password", b"salt", 2, 32,
     "ae4d0c95af6b46d32d0adff928f06dd02a303f8ef3c251dfd6e2d85a95474c43"),
    ("password", b"salt", 4096, 32,
     "c5e478d59288c841aa530db6845c4c8d962893a001ce4e11a4963873aa98134a"),
]


def derive(password, salt_hex, iterations, dklen):
    """PBKDF2-HMAC-SHA256 as lowercase hex."""
    derived = hashlib.pbkdf2_hmac(
        "sha256",
        password.encode("utf-8"),  # ASCII by construction
        bytes.fromhex(salt_hex),
        iterations,
        dklen,
    )
    return derived.hex()


def self_check():
    for password, salt, iterations, dklen, expected in SELF_CHECK:
        got = hashlib.pbkdf2_hmac(
            "sha256", password.encode("utf-8"), salt, iterations, dklen
        ).hex()
        if got != expected:
            sys.stderr.write(
                "SELF-CHECK FAILED: pbkdf2_hmac(sha256, %r, %r, %d) = %s, expected %s\n"
                % (password, salt, iterations, got, expected)
            )
            sys.stderr.write("Refusing to emit vectors from a broken KDF.\n")
            return False
    sys.stderr.write(
        "self-check: hashlib matches the published PBKDF2-HMAC-SHA256 vectors\n"
    )
    return True


def emit_cpp(rows):
    out = []
    out.append("// Generated by scripts/gen_pbkdf2_vectors.py -- do not edit by hand.")
    out.append("// Expected values derived independently with Python hashlib.pbkdf2_hmac")
    out.append("// (sha256), cross-checked against the published PBKDF2-HMAC-SHA256 vectors.")
    out.append("// Compare against vpn::crypto::pbkdf2_sha256(password, salt, iterations).")
    out.append("struct Pbkdf2Sha256Vector {")
    out.append("  const char* name;")
    out.append("  const char* password;  // ASCII")
    out.append("  const char* salt_hex;  // lowercase hex")
    out.append("  unsigned iterations;")
    out.append("  unsigned dklen;")
    out.append("  const char* expected_hex;  // lowercase hex, dklen bytes")
    out.append("};")
    out.append("")
    out.append("inline constexpr Pbkdf2Sha256Vector kPbkdf2Sha256Vectors[] = {")
    for name, password, salt_hex, iterations, dklen, expected in rows:
        out.append(
            '    {"%s", "%s", "%s", %d, %d,\n     "%s"},'
            % (name, password, salt_hex, iterations, dklen, expected)
        )
    out.append("};")
    out.append(
        "inline constexpr unsigned kPbkdf2Sha256VectorCount = "
        "sizeof(kPbkdf2Sha256Vectors) / sizeof(kPbkdf2Sha256Vectors[0]);"
    )
    return "\n".join(out) + "\n"


def emit_text(rows):
    out = []
    out.append("PBKDF2-HMAC-SHA256 known-answer vectors (dklen in bytes)")
    out.append("")
    header = "%-20s %-28s %-34s %10s %5s  %s" % (
        "name", "password", "salt_hex", "iterations", "dklen", "expected_hex")
    out.append(header)
    out.append("-" * len(header))
    for name, password, salt_hex, iterations, dklen, expected in rows:
        shown = '"%s"' % password if password else "(empty)"
        out.append("%-20s %-28s %-34s %10d %5d  %s" % (
            name, shown, salt_hex, iterations, dklen, expected))
    return "\n".join(out) + "\n"


def emit_json(rows):
    payload = {
        "algorithm": "PBKDF2-HMAC-SHA256",
        "reference": "RFC 8018 section 5.2",
        "produced_by": "python hashlib.pbkdf2_hmac('sha256', ...)",
        "vectors": [
            {
                "name": name,
                "password": password,
                "salt_hex": salt_hex,
                "iterations": iterations,
                "dklen": dklen,
                "expected_hex": expected,
            }
            for name, password, salt_hex, iterations, dklen, expected in rows
        ],
    }
    return json.dumps(payload, indent=2) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Emit PBKDF2-HMAC-SHA256 known-answer vectors as C++ test data."
    )
    parser.add_argument(
        "--format", choices=("cpp", "text", "json"), default="cpp",
        help="output format (default: cpp, a C++ table)")
    parser.add_argument(
        "--password", default=None,
        help="add one extra vector for this ASCII password")
    parser.add_argument(
        "--salt-hex", default=DEFAULT_SALT_HEX,
        help="salt for --password (lowercase hex, default: 0011...eeff)")
    parser.add_argument(
        "--iterations", type=int, default=120000,
        help="work factor for --password (default: 120000)")
    parser.add_argument(
        "--dklen", type=int, default=32,
        help="derived key length in bytes for --password (default: 32)")
    parser.add_argument(
        "--no-self-check", action="store_true",
        help="skip the published-vector self-check (debugging this script only)")
    args = parser.parse_args(argv)

    if args.no_self_check:
        sys.stderr.write("self-check: SKIPPED on request\n")
    elif not self_check():
        return 3

    rows = []
    for name, password, salt_hex, iterations, dklen in VECTORS:
        if dklen < 1 or dklen > 1024:
            sys.stderr.write("dklen out of range for %s\n" % name)
            return 2
        if iterations < 1:
            sys.stderr.write("iterations out of range for %s\n" % name)
            return 2
        try:
            bytes.fromhex(salt_hex)
        except ValueError:
            sys.stderr.write("salt for %s is not valid hex\n" % name)
            return 2
        rows.append((name, password, salt_hex, iterations, dklen,
                     derive(password, salt_hex, iterations, dklen)))

    if args.password is not None:
        try:
            bytes.fromhex(args.salt_hex)
        except ValueError:
            sys.stderr.write("--salt-hex is not valid hex\n")
            return 2
        if args.dklen < 1 or args.dklen > 1024 or args.iterations < 1:
            sys.stderr.write("--dklen/--iterations out of range\n")
            return 2
        rows.append(("custom", args.password, args.salt_hex.lower(), args.iterations,
                     args.dklen,
                     derive(args.password, args.salt_hex, args.iterations, args.dklen)))

    emitter = {"cpp": emit_cpp, "text": emit_text, "json": emit_json}[args.format]
    sys.stdout.write(emitter(rows))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

