# Reproducible local build for the vpn server on Windows without MSVC.
#
# The toolchain is zig's bundled clang (clang++/libc++/MinGW-w64 headers) driven
# through CMake + Ninja. CMake needs a single executable per tool, so this script
# generates thin .cmd shims for `zig c++`, `zig ar` and `zig ranlib`.
#
# Usage:
#   pwsh -File scripts/build-local.ps1                 # Release, warnings-as-errors
#   pwsh -File scripts/build-local.ps1 -BuildType Debug
#   pwsh -File scripts/build-local.ps1 -Clean
#
# Exit code is 0 only if the build AND the test suite both pass.

[CmdletBinding()]
param(
    [ValidateSet('Release', 'Debug')]
    [string]$BuildType = 'Release',
    [switch]$Clean,
    [string]$Zig,
    [switch]$SkipTests,
    # LLVM (inside zig) needs ~1-2 GB per translation unit; on a 16 GB machine
    # `--parallel` (all cores) can exhaust memory. 2 keeps the box responsive.
    [int]$Jobs = 2
)

$ErrorActionPreference = 'Stop'
$repo = Split-Path -Parent $PSScriptRoot
$out = Join-Path $repo 'out'
$tools = Join-Path $out 'tools'
$buildDir = Join-Path $out "build-$($BuildType.ToLower())"

function Find-Zig {
    param([string]$Explicit)
    $candidates = @()
    if ($Explicit) { $candidates += $Explicit }
    if ($env:VPN_ZIG) { $candidates += $env:VPN_ZIG }
    $candidates += (Join-Path $env:USERPROFILE '.local\pylibs\ziglang\zig.exe')
    $candidates += (Join-Path $env:USERPROFILE '.local\toolchains\zig016\zig\ziglang\zig.exe')
    $candidates += (Join-Path $env:USERPROFILE '.local\toolchains\zig\ziglang\zig.exe')
    $candidates += (Join-Path $repo 'server\tests\golden\work\zig\ziglang\zig.exe')
    $onPath = Get-Command zig -ErrorAction SilentlyContinue
    if ($onPath) { $candidates += $onPath.Source }
    foreach ($c in $candidates) {
        if ($c -and (Test-Path -LiteralPath $c)) { return (Resolve-Path -LiteralPath $c).Path }
    }
    throw "zig.exe not found. Pass -Zig <path> or set VPN_ZIG."
}

function Expand-ToolchainZip {
    param([string]$Zip, [string]$Destination)
    if (-not (Test-Path -LiteralPath $Zip)) { return $false }
    $len = (Get-Item -LiteralPath $Zip).Length
    if ($len -lt 1024) {
        Write-Warning "ignoring $Zip (only $len bytes - truncated download)"
        return $false
    }
    New-Item -ItemType Directory -Force -Path $Destination | Out-Null
    Add-Type -AssemblyName System.IO.Compression.FileSystem
    # Absolute paths: .NET file APIs resolve against the process CWD, not the
    # PowerShell location, so a relative destination silently lands elsewhere.
    [System.IO.Compression.ZipFile]::ExtractToDirectory((Resolve-Path -LiteralPath $Zip).Path, $Destination)
    return $true
}

function Find-Tool {
    param([string]$Name, [string]$SearchRoot)
    $hit = Get-ChildItem -LiteralPath $SearchRoot -Recurse -Filter $Name -ErrorAction SilentlyContinue |
        Select-Object -First 1
    if ($hit) { return $hit.FullName }
    $onPath = Get-Command ([System.IO.Path]::GetFileNameWithoutExtension($Name)) -ErrorAction SilentlyContinue
    if ($onPath) { return $onPath.Source }
    return $null
}

# --- toolchain discovery ------------------------------------------------------
$zigExe = Find-Zig -Explicit $Zig
Write-Host "zig      : $zigExe ($(& $zigExe version))"

$toolsRoot = Join-Path $env:USERPROFILE '.local\toolchains'
New-Item -ItemType Directory -Force -Path $tools | Out-Null

$cmakeExe = Find-Tool -Name 'cmake.exe' -SearchRoot $tools
if (-not $cmakeExe) {
    if (Expand-ToolchainZip -Zip (Join-Path $toolsRoot 'cmake.zip') -Destination (Join-Path $tools 'cmake')) {
        $cmakeExe = Find-Tool -Name 'cmake.exe' -SearchRoot (Join-Path $tools 'cmake')
    }
}
if (-not $cmakeExe) { throw "cmake.exe not found. Expected it under $toolsRoot\cmake.zip or on PATH." }

$ninjaExe = Find-Tool -Name 'ninja.exe' -SearchRoot $tools
if (-not $ninjaExe) {
    if (Expand-ToolchainZip -Zip (Join-Path $toolsRoot 'ninja.zip') -Destination (Join-Path $tools 'ninja')) {
        $ninjaExe = Find-Tool -Name 'ninja.exe' -SearchRoot (Join-Path $tools 'ninja')
    }
}
if (-not $ninjaExe) { throw "ninja.exe not found. Expected it under $toolsRoot\ninja.zip or on PATH." }

Write-Host "cmake    : $cmakeExe"
Write-Host "ninja    : $ninjaExe"

# --- compiler shims -----------------------------------------------------------
# CMake takes exactly one executable per tool, so forward to zig's subcommands.
function Write-Shim {
    param([string]$Path, [string]$Subcommand)
    $body = "@echo off`r`nrem Generated by scripts/build-local.ps1 - do not edit.`r`n`"$zigExe`" $Subcommand %*`r`n"
    Set-Content -LiteralPath $Path -Value $body -Encoding ascii -NoNewline
    return $Path
}

$cxxShim = Write-Shim -Path (Join-Path $tools 'zig-cxx.cmd') -Subcommand 'c++'
$arShim = Write-Shim -Path (Join-Path $tools 'zig-ar.cmd') -Subcommand 'ar'
$ranlibShim = Write-Shim -Path (Join-Path $tools 'zig-ranlib.cmd') -Subcommand 'ranlib'

if ($Clean -and (Test-Path -LiteralPath $buildDir)) {
    Write-Host "cleaning : $buildDir"
    Remove-Item -LiteralPath $buildDir -Recurse -Force
}

# --- configure ----------------------------------------------------------------
# CMAKE_CXX_SCAN_FOR_MODULES=OFF: CMake 3.28+ otherwise requires clang-scan-deps
# next to the compiler, which a zig shim does not have. The project uses no
# C++ modules, so scanning buys nothing.
$slash = { param($p) $p -replace '\\', '/' }
& $cmakeExe -S $repo -B $buildDir -G Ninja `
    "-DCMAKE_CXX_COMPILER=$(& $slash $cxxShim)" `
    "-DCMAKE_AR=$(& $slash $arShim)" `
    "-DCMAKE_RANLIB=$(& $slash $ranlibShim)" `
    "-DCMAKE_MAKE_PROGRAM=$(& $slash $ninjaExe)" `
    "-DCMAKE_BUILD_TYPE=$BuildType" `
    -DVPN_WARNINGS_AS_ERRORS=ON `
    -DCMAKE_CXX_SCAN_FOR_MODULES=OFF
if ($LASTEXITCODE -ne 0) { throw "cmake configure failed ($LASTEXITCODE)" }

# --- build --------------------------------------------------------------------
& $cmakeExe --build $buildDir --parallel $Jobs
if ($LASTEXITCODE -ne 0) { throw "build failed ($LASTEXITCODE)" }

if ($SkipTests) { Write-Host 'tests skipped (-SkipTests)'; exit 0 }

# --- test ---------------------------------------------------------------------
& $cmakeExe --build $buildDir --target test
if ($LASTEXITCODE -ne 0) { throw "tests failed ($LASTEXITCODE)" }

Write-Host ''
Write-Host "OK - $BuildType build + tests green"
exit 0
